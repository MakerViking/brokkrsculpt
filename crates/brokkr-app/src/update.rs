    /// **The only clock value this design stores, and it must never refuse
    /// anything.** That is the whole difference from the `expires` field the
    /// plan rejected: a wrong clock costs a sentence in the Help panel, not the
    /// ability to update.
    #[test]
    fn freshness_is_reported_and_never_enforced() {
        let day = 86_400;
        assert_eq!(days_since_check("last_check = 1000", 1000 + day), Some(1));
        assert_eq!(days_since_check("last_check = 1000", 1000 + 10 * day), Some(10));
        assert_eq!(days_since_check("last_check = 1000", 1000), Some(0));
        // Never recorded.
        assert_eq!(days_since_check("", 1000), None);
        assert_eq!(days_since_check("last_check = banana", 1000), None);
        // A clock that went backwards -- a fresh VM before NTP, a dead CMOS
        // battery -- reads as unknown rather than as a negative age, and above
        // all does not panic on the subtraction.
        assert_eq!(days_since_check("last_check = 9999", 1000), None);
    }

    /// `update.state` is rewritten whole, so a field written by one call must
