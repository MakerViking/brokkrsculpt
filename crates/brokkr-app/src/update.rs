    /// `skip_build` answers an offer. It does not answer "the build you are on
    /// is known broken", and conflating the two would silence the one message
    /// that matters most.
    #[test]
    fn the_offer_wording_never_claims_a_direction_it_does_not_have() {
        let up = Offer {
            build: 1018,
            running: 1012,
            known_bad: false,
            requires_reinstall: false,
            payload: None,
            seq: 1,
            key_epoch: 0,
        };
        assert!(up.headline().contains("1018"));
        assert!(up.headline().starts_with("Build 1018 is out"));

        // A rollback offers a LOWER ordinal. It must not read as an upgrade.
        let down = Offer {
            build: 1012,
            running: 1018,
            known_bad: false,
            requires_reinstall: false,
            payload: None,
            seq: 1,
            key_epoch: 0,
        };
        assert!(!down.headline().contains("is out"), "got {:?}", down.headline());

        let bad = Offer {
            build: 1031,
            running: 1012,
            known_bad: true,
            requires_reinstall: false,
            payload: None,
            seq: 1,
            key_epoch: 0,
        };
        assert!(bad.headline().contains("known problem"));
        assert!(bad.headline().contains("1012") && bad.headline().contains("1031"));
    }
