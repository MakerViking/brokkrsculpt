    /// Verify against the test key rather than the shipped ones, so these tests
    /// exercise the real code path without the production keys' secret halves
    /// existing anywhere a test could reach.
    fn verify_with(keys: &[(u32, &str)], body: &[u8], sig: &[u8]) -> Result<Manifest, Refusal> {
        let signature =
            std::str::from_utf8(sig).map_err(|why| Refusal::MalformedSignature(why.to_string()))?;
        let decoded = minisign_verify::Signature::decode(signature)
            .map_err(|why| Refusal::MalformedSignature(why.to_string()))?;
        let mut last = String::new();
        let mut signed_by = None;
        for (epoch, encoded) in keys {
            let Ok(key) = minisign_verify::PublicKey::from_base64(encoded) else { continue };
            match key.verify(body, &decoded, false) {
                Ok(()) => {
                    signed_by = Some(*epoch);
                    break;
                }
                Err(why) => last = why.to_string(),
            }
        }
        let signed_by = signed_by.ok_or(Refusal::NotSignedByUs(last))?;
        let text = std::str::from_utf8(body).map_err(|_| Refusal::BadField("utf8".into()))?;
        let manifest = parse_manifest(text, signed_by)?;
        if manifest.key_epoch != signed_by {
            return Err(Refusal::EpochDisagrees { declared: manifest.key_epoch, signed_by });
        }
        if manifest.seq > MAX_SEQ {
            return Err(Refusal::SeqImplausible(manifest.seq));
        }
        Ok(manifest)
    }

