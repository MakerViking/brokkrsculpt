//! Noticing that a newer build exists, from a source that can be authenticated.
//!
//! Replaces `update_check.rs`, which asked the GitHub API for the `beta`
//! release's `target_commitish` and compared it to `build_commit()`. That could
//! only ever say *different*, never *newer* -- a git SHA has no order -- and it
//! authenticated nothing: whoever answered the request decided what the user was
//! told. It also polled `api.github.com`, which is rate limited to sixty
//! requests an hour per address, so one makerspace behind one NAT broke it for
//! everyone there, silently, because failure here is deliberately silence.
//!
//! # What this module is
//!
//! Checking, fetching and verifying: the manifest, its signature, the key list
//! and its epochs, the anti-rollback floor, and the payload download with its
//! digest. Putting a verified file in place is [`apply`], which is where every
//! platform difference lives.
//!
//! Four things here had to be right in the *first* shipped binary because they
//! cannot be retrofitted onto copies already in the field: the key list and its
//! epochs, the anti-rollback floor and which number space it lives in, unknown
//! manifest keys being ignored rather than rejected, and `requires_reinstall`.
//!
//! # Two number spaces, and they must never be compared to each other
//!
//! - **`build`** counts CI runs. `1000 + github.run_number`, stamped by
//!   `release.yml`, read back by [`crate::app::build_number`]. It identifies a
//!   *payload*.
//! - **`seq`** counts manifests. Generated by `scripts/sign-release.sh`, which
//!   refuses to sign unless it strictly increases. It identifies a *release
//!   decision*.
//!
//! They diverge by construction the moment a rollback happens: publishing a
//! manifest with `seq + 1` naming an older `build` is how a bad release is
//! walked back. So the anti-rollback floor is compared **only** against `seq`,
//! and `minimum_build` **only** against `build`. Mixing them warns the whole
//! fleet or none of it, and on a fresh install it would set a floor of 1005
//! against a `seq` counter that starts at 1 -- silently refusing every manifest
//! that will ever be published.
//!
//! # Verify, then parse
//!
//! `key_epoch` is a manifest field, so choosing the key by reading it means
//! parsing attacker bytes to decide which key says whether they are attacker
//! bytes. The order here is: decode the signature container, try each compiled-in
//! key until one verifies, keep the epoch **from our own key list**, and only
//! then parse. See [`verify_manifest`].

use std::fmt;

/// Putting a verified file in place, on all three platforms. See the module.
pub mod apply;

/// The keys that may sign a manifest, each with the epoch it *is* -- never the
/// epoch of its position in this slice.
///
/// **Append only, and the numbers do not close up.** The epoch is a field rather
/// than an index because this list shrinks as well as grows: recovering from a
/// leak means shipping a build that DROPS the compromised key and appends a
/// fresh standby, and dropping index 0 would renumber everything after it. A
/// client that had persisted `floor_epoch = 1` would then refuse the very build
/// sent to rescue it. After a rotation this list reads `&[(1, STANDBY),
/// (2, FRESH)]` -- no epoch 0, and no ambiguity about which key that is.
///
/// Generated 2026-08-30 on Thomas's machine with `minisign -G`. Epoch 0 is the
/// live key (id `B6D059FAFC11CF4C`); epoch 1 is the standby (id
/// `BDB38C17AB97C0FD`), whose secret half is held off the build machine so a
/// leak of the live key has a recovery path. **Where** it is held is recorded in
/// `handoff.md` and deliberately not here: this file is public, and a public
/// file naming the two places a signing key is backed up turns a document into
/// a target list. SECURITY.md describes the rotation mechanism without the
/// locations, which is the part a reader actually needs.
///
/// Only the public halves are here, which is the
/// whole point: a compiled-in public key is the only root of trust available,
/// because there is no Apple Developer ID and no Authenticode certificate to
/// make the operating system vouch for anything.
const TRUSTED_KEYS: &[(u32, &str)] = &[
    (0, "RWRMzxH8+lnQtk8qdxGmcdtqvNehqg9aNbBOS93i8EnPzycE+6wBvZeJ"),
    (1, "RWT9wJerF4yzvRVZh7HQcd4eHrwx6z5bMU9LQB2mdrhqFPf10K6PthPw"),
];

/// Where a payload may be fetched from, compiled in rather than supplied by the
/// manifest.
///
/// **This is what bounds a leaked key.** The manifest names a *filename* and
/// never a URL, so an attacker holding the signing key can sign a manifest and
/// still cannot serve one: they would also need write access to a GitHub release
/// they do not control. Two independent things must fail, and even then the
/// worst outcome is a downgrade to one of our own previously published builds,
/// because every digest they sign still has to match bytes we published.
const DOWNLOAD_PREFIX: &str = "https://github.com/MakerViking/brokkrsculpt/releases/download/beta/";

/// The absolute ceiling on a payload, compiled in and enforced **first**.
///
/// The signed `size` is a *secondary tightening* applied after the signature
/// verifies. Using the declared size as the only cap would let anyone who can
/// answer the request make us stream gigabytes into the user's directory before
/// the digest check fails. `MAX_THUMB_BYTES` in `articles.rs` is the precedent,
/// and it is the right one precisely because it is a constant the far end
/// cannot set.
const MAX_UPDATE_BYTES: u64 = 128 * 1024 * 1024;

/// The manifest and its signature, as plain release-download URLs rather than
/// API calls. Asset URLs go through the CDN with no rate limit; the API poll
/// this replaces had sixty an hour per address.
const MANIFEST_URL: &str =
    "https://github.com/MakerViking/brokkrsculpt/releases/download/beta/latest.conf";
const SIGNATURE_URL: &str =
    "https://github.com/MakerViking/brokkrsculpt/releases/download/beta/latest.conf.minisig";

/// Absolute caps on the two things fetched before anything is trusted.
///
/// Compiled in, and enforced before the signature is checked, because at that
/// point every byte is attacker controlled. A manifest is a few hundred bytes
/// and a signature is two lines; these are three orders of magnitude of slack.
const MAX_MANIFEST_BYTES: u64 = 64 * 1024;
const MAX_SIGNATURE_BYTES: u64 = 4 * 1024;

/// Structural caps inside the manifest. A line count as well as a byte count,
/// because 64 KiB of one-character lines is a different denial of service from
/// 64 KiB of one line.
const MAX_MANIFEST_LINES: usize = 200;
const MAX_FIELD_BYTES: usize = 256;

/// The largest ordinal a manifest may claim.
///
/// Bounds a poisoned floor: the floor advances on a successful apply, so an
/// attacker holding the key could otherwise sign an enormous `seq` over a
/// genuinely published payload and leave every client that took it with a floor
/// no honest release will ever clear.
///
/// An absolute constant rather than a comparison against the running build,
/// which an earlier draft specified: that mixes the two number spaces. It cannot
/// be relative to the floor either, because a fresh install seeds `floor_seq = 0`
/// and is the *most* exposed. At the measured cadence -- four releases in one
/// afternoon -- a million is well over a century.
const MAX_SEQ: u64 = 1_000_000;

/// The platform this binary would look for in a manifest.
///
/// `None` on anything else, which means the updater is inert there rather than
/// guessing. The strings match the `slug` values in `release.yml`'s matrix.
const fn platform_slug() -> Option<&'static str> {
    if cfg!(all(target_os = "linux", target_arch = "x86_64")) {
        Some("linux-x86_64")
    } else if cfg!(all(target_os = "windows", target_arch = "x86_64")) {
        Some("windows-x86_64")
    } else if cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        Some("macos-arm64")
    } else {
        None
    }
}

/// One platform's payload, as the manifest describes it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Payload {
    /// A bare filename. Never a URL, and validated by [`valid_payload_name`].
    pub name: String,
    /// Bytes, exactly. A secondary tightening applied *after* the signature
    /// verifies -- the absolute cap is what protects the download itself.
    pub size: u64,
    /// Lowercase hex, 64 characters, already syntax-checked.
    pub sha256: String,
}

/// A manifest that has been verified and then parsed, in that order.
///
/// Construction is only possible through [`verify_manifest`], which is the point:
/// there is no way to hold one of these that did not come from bytes a compiled-in
/// key signed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Manifest {
    /// Manifest space. Compared against the persisted floor, never against a build.
    pub seq: u64,
    /// Build space. The ordinal of the payload this manifest offers.
    pub build: u64,
    /// Which key signed it, cross-checked against the key that actually verified.
    pub key_epoch: u32,
    /// Build space. A running build strictly below this gets a stronger warning.
    pub minimum_build: u64,
    /// Whether this build can be reached by replacing one executable.
    pub requires_reinstall: bool,
    /// This platform's payload, if the manifest names one. Absent means "no
    /// update for this platform", which is an ordinary outcome and not an error.
    pub payload: Option<Payload>,
}

/// Why an offer was refused.
///
/// **Every one of these is a named rejection**, never a default and never a
/// saturating fallback. These are attacker-controlled bytes at a point where
/// nothing is trusted yet, and "the field was missing so we used zero" is how a
/// manifest with no `minimum_build` silently disables a warning.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Refusal {
    /// This build was not stamped by the release pipeline, is dirty, or is
    /// running out of a `target/` directory. The updater is inert.
    NotAReleaseBuild,
    /// No platform payload could apply here.
    UnsupportedPlatform,
    /// The network did not answer, or answered with a status.
    Unreachable(String),
    /// Larger than a compiled-in cap, before anything was trusted.
    TooLarge { what: &'static str, cap: u64 },
    /// The signature file was not valid UTF-8, or minisign could not parse it.
    MalformedSignature(String),
    /// No trusted key verified it. Covers a wrong key, a tampered manifest and a
    /// legacy `Ed` signature alike -- all of them mean the same thing to a user.
    NotSignedByUs(String),
    /// A required field was absent, unparseable, duplicated, or too long.
    BadField(String),
    /// The manifest declared an epoch that is not the one that signed it. Not an
    /// attack: a release-night mistake, which would otherwise persist a
    /// `floor_epoch` no key can satisfy again.
    EpochDisagrees { declared: u32, signed_by: u32 },
    /// Older than this install has already accepted.
    BelowFloor { seq: u64, floor: u64 },
    /// Signed by a key this install has already superseded.
    EpochBelowFloor { epoch: u32, floor: u32 },
    /// Implausible ordinal; see [`MAX_SEQ`].
    SeqImplausible(u64),
    /// The payload was not the length the signed manifest declared. Named
    /// separately from a digest mismatch because the two mean different things
    /// to a user: this one is usually a truncated download.
    PayloadSizeMismatch { declared: u64, actual: u64 },
    /// The payload's SHA-256 did not match the signed one. Nothing is made
    /// executable on this path.
    DigestMismatch { expected: String, actual: String },
    /// This install cannot replace itself here, with the reason. Covers a
    /// system install, a directory other users can write, and a filesystem that
    /// said no -- all of which mean "update it the way you installed it".
    CannotReplace(String),
    /// Another copy of the application holds the update lock.
    AlreadyUpdating,
    /// This copy downloads and hands over rather than replacing itself.
    ///
    /// Three ways to get here: `BROKKR_NO_SELF_UPDATE=1`; a `.app` bundle on a
    /// platform with no whole-bundle path, since editing one in place would
    /// leave a half-swapped application; and any future platform with no
    /// replacement of its own.
    HandOverOnly,
    /// The staged file vanished between writing it and installing it. On
    /// Windows that means an antivirus quarantined it, which retrying cannot
    /// fix -- a self-rewriting `.exe` is a textbook Defender heuristic, so
    /// deletion is at least as likely as a sharing violation.
    ///
    Quarantined,
}

impl fmt::Display for Refusal {
    /// Worded for a status line, because there is no terminal to read anything
    /// else in. A refusal the user cannot act on still says which number was
    /// wrong -- a silent permanent refusal is indistinguishable from a network
    /// that stopped answering.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NotAReleaseBuild => write!(f, "this build does not update itself"),
            Self::UnsupportedPlatform => write!(f, "no update is published for this platform"),
            Self::Unreachable(why) => write!(f, "could not check for updates ({why})"),
            Self::TooLarge { what, cap } => write!(f, "the {what} was larger than {cap} bytes"),
            Self::MalformedSignature(why) => write!(f, "the update signature is malformed ({why})"),
            Self::NotSignedByUs(why) => {
                write!(f, "the update was not signed by BrokkrSculpt ({why})")
            }
            Self::BadField(why) => write!(f, "the update manifest is malformed ({why})"),
            Self::EpochDisagrees { declared, signed_by } => {
                write!(f, "the update names key {declared} but was signed by key {signed_by}")
            }
            Self::BelowFloor { seq, floor } => {
                write!(f, "ignoring update {seq}: this install has already accepted {floor}")
            }
            Self::EpochBelowFloor { epoch, floor } => {
                write!(f, "ignoring an update signed by key {epoch}: this install requires {floor}")
            }
            Self::SeqImplausible(seq) => {
                write!(f, "the update claims an implausible number ({seq})")
            }
            Self::PayloadSizeMismatch { declared, actual } => {
                write!(f, "the download was {actual} bytes, not the {declared} it should be")
            }
            Self::DigestMismatch { .. } => {
                write!(f, "the download did not match its signature and was discarded")
            }
            Self::CannotReplace(why) => write!(f, "this copy cannot update itself: {why}"),
            Self::AlreadyUpdating => {
                write!(f, "another copy of BrokkrSculpt is installing an update")
            }
            Self::HandOverOnly => write!(
                f,
                "this copy cannot install updates itself -- the download has been verified and \
                 saved, and replacing the application is a manual step"
            ),
            Self::Quarantined => write!(
                f,
                "the downloaded update was removed before it could be installed, most likely by \
                 antivirus -- nothing was changed"
            ),
        }
    }
}

/// The anti-rollback floor this install has written for itself.
///
/// Seeded at **zero** on a fresh install -- see the module header. It advances
/// only on a successful apply, never on merely seeing an offer, so an attacker
/// who can show a client a manifest cannot move its floor by doing so.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Floor {
    pub epoch: u32,
    pub seq: u64,
}

/// Verify a manifest's signature, then parse it. In that order, and the order is
/// the entire point of this function.
///
/// # Why the key is found by trying rather than by reading an id
///
/// minisign signatures carry the 8-byte id of the key that made them, and
/// `PublicKey::verify` compares it as its first statement -- before the Blake2b
/// prehash and before Ed25519. But `minisign-verify` 0.2.5 exposes no accessor
/// for it: `key_id` is private on both `Signature` and `PublicKey`. So selection
/// is a loop over [`TRUSTED_KEYS`], and it is cheap for exactly that reason: a
/// wrong key costs one base64 decode and one integer compare, not a signature
/// check. Against a two-entry list that is nothing.
///
/// The epoch is taken from the entry that verified, never from its position, and
/// the parsed `key_epoch` must then agree with it.
///
/// # Neither comment is ever read
///
/// `untrusted_comment` is unsigned, so it is straightforwardly attacker text.
/// `trusted_comment` is the trap, because it *does* verify -- the global
/// signature covers `signature || trusted_comment`. Verified is not validated:
/// none of the caps or named rejections below reach it, and reading it would
/// create a second channel of meaning running beside the manifest with nothing
/// binding the two together. A trusted comment saying `build:1018` next to a
/// manifest saying `build:1012` is a state no code here would notice.
pub fn verify_manifest(body: &[u8], signature: &[u8]) -> Result<Manifest, Refusal> {
    if body.len() as u64 > MAX_MANIFEST_BYTES {
        return Err(Refusal::TooLarge { what: "update manifest", cap: MAX_MANIFEST_BYTES });
    }
    if signature.len() as u64 > MAX_SIGNATURE_BYTES {
        return Err(Refusal::TooLarge { what: "update signature", cap: MAX_SIGNATURE_BYTES });
    }

    // `Signature::decode` takes `&str`, so the bytes off the wire get a UTF-8
    // check here and a non-UTF-8 `.minisig` is a named rejection rather than a
    // panic somewhere later.
    let signature = std::str::from_utf8(signature)
        .map_err(|why| Refusal::MalformedSignature(why.to_string()))?;
    let decoded = minisign_verify::Signature::decode(signature)
        .map_err(|why| Refusal::MalformedSignature(why.to_string()))?;

    let mut last_error = String::from("no trusted key was tried");
    let mut signed_by = None;
    for (epoch, encoded) in TRUSTED_KEYS {
        let key = match minisign_verify::PublicKey::from_base64(encoded) {
            Ok(key) => key,
            // A malformed entry in our own compiled-in list. Not reachable
            // without a code change, and not a reason to trust anything else.
            Err(why) => {
                last_error = why.to_string();
                continue;
            }
        };
        // `false` is `allow_legacy`. A legacy `Ed` signature fails here with
        // `UnexpectedAlgorithm`; `UnsupportedLegacyMode` is what `verify_stream`
        // returns and we do not call it, because the manifest is small and is
        // verified in one shot.
        match key.verify(body, &decoded, false) {
            Ok(()) => {
                signed_by = Some(*epoch);
                break;
            }
            Err(why) => last_error = why.to_string(),
        }
    }
    let Some(signed_by) = signed_by else {
        return Err(Refusal::NotSignedByUs(last_error));
    };

    // Only now are these bytes worth parsing.
    let text = std::str::from_utf8(body)
        .map_err(|why| Refusal::BadField(format!("not valid UTF-8: {why}")))?;
    let manifest = parse_manifest(text, signed_by)?;

    if manifest.key_epoch != signed_by {
        return Err(Refusal::EpochDisagrees { declared: manifest.key_epoch, signed_by });
    }
    if manifest.seq > MAX_SEQ {
        return Err(Refusal::SeqImplausible(manifest.seq));
    }
    Ok(manifest)
}

/// Parse a manifest that has already been verified.
///
/// Separate from [`verify_manifest`] only so the caller cannot accidentally
/// invoke it on unverified bytes -- it is private, and the public entry point
/// verifies first.
///
/// **Unknown keys are ignored, not rejected**, and that is a v1 format decision
/// with no retrofit. Rejecting them means the format can never gain a field
/// without breaking every client already in the field, and the remedy would have
/// to travel down the channel the mistake is in. It costs nothing here because
/// the manifest is signed as a whole: nothing can smuggle meaning into a field
/// no code reads, and the fields that *are* read are each validated by name.
///
/// **Duplicate keys ARE rejected.** `paths::entries` yields them happily and a
/// last-wins collect would let a manifest carry two `build` lines and have the
/// client and a human reading the file disagree about which one counts.
fn parse_manifest(text: &str, _signed_by: u32) -> Result<Manifest, Refusal> {
    if text.lines().count() > MAX_MANIFEST_LINES {
        return Err(Refusal::BadField(format!("more than {MAX_MANIFEST_LINES} lines")));
    }

    let mut fields: Vec<(&str, &str)> = Vec::new();
    for (key, value) in crate::paths::entries(text) {
        if key.len() > MAX_FIELD_BYTES || value.len() > MAX_FIELD_BYTES {
            return Err(Refusal::BadField(format!(
                "`{key}` is longer than {MAX_FIELD_BYTES} bytes"
            )));
        }
        if fields.iter().any(|(seen, _)| *seen == key) {
            return Err(Refusal::BadField(format!("`{key}` appears twice")));
        }
        fields.push((key, value));
    }
    let get = |name: &str| fields.iter().find(|(key, _)| *key == name).map(|(_, value)| *value);

    // Every required field is fetched the same way: absent is an error, and
    // unparseable is a *different* error naming the field. Neither is a default.
    let number = |name: &str| -> Result<u64, Refusal> {
        let raw = get(name).ok_or_else(|| Refusal::BadField(format!("`{name}` is missing")))?;
        raw.parse::<u64>()
            .map_err(|_| Refusal::BadField(format!("`{name}` is not a number: {raw:?}")))
    };

    let seq = number("seq")?;
    let build = number("build")?;
    let minimum_build = number("minimum_build")?;
    let key_epoch = u32::try_from(number("key_epoch")?)
        .map_err(|_| Refusal::BadField("`key_epoch` is out of range".into()))?;
    // Required rather than optional-defaulting-to-zero, for the same reason as
    // `minimum_build`: a field that silently disables itself when omitted is
    // discovered on the release where it mattered.
    let requires_reinstall = match number("requires_reinstall")? {
        0 => false,
        1 => true,
        other => {
            return Err(Refusal::BadField(format!(
                "`requires_reinstall` must be 0 or 1, not {other}"
            )));
        }
    };

    // An absent platform block means "no update for this platform". An absent
    // *field* inside a block that exists is malformed, which is a different
    // thing and gets a different answer.
    let payload = match platform_slug() {
        None => None,
        Some(slug) => {
            let name_key = format!("{slug}.name");
            match get(&name_key) {
                None => None,
                Some(name) => {
                    if !valid_payload_name(name) {
                        return Err(Refusal::BadField(format!(
                            "`{name_key}` is not a plain filename: {name:?}"
                        )));
                    }
                    let size = number(&format!("{slug}.size"))?;
                    let sha_key = format!("{slug}.sha256");
                    let sha256 = get(&sha_key)
                        .ok_or_else(|| Refusal::BadField(format!("`{sha_key}` is missing")))?;
                    if sha256.len() != 64 || !sha256.bytes().all(|b| b.is_ascii_hexdigit()) {
                        return Err(Refusal::BadField(format!("`{sha_key}` is not 64 hex digits")));
                    }
                    Some(Payload {
                        name: name.to_string(),
                        size,
                        sha256: sha256.to_ascii_lowercase(),
                    })
                }
            }
        }
    };

    Ok(Manifest { seq, build, key_epoch, minimum_build, requires_reinstall, payload })
}

/// Whether a manifest-supplied name is a plain filename and nothing else.
///
/// The URL is built by concatenating [`DOWNLOAD_PREFIX`] with this, so anything
/// that could climb out of that prefix -- a slash, a backslash, a `..`, a scheme
/// -- has to be refused here or the compiled-in prefix stops bounding anything.
/// An allowlist rather than a denylist, because the set of characters that are
/// safe is small and knowable and the set that is dangerous is neither.
fn valid_payload_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= MAX_FIELD_BYTES
        && name != ".."
        && !name.contains("..")
        && name.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
}

/// Whether a verified manifest may be acted on by this install, given its floor.
///
/// Separate from verification because it answers a different question.
/// Verification asks *who signed this*; this asks *may they still*. A leaked key
/// stays compiled in until a new binary ships, so its signatures go on verifying
/// for ever -- this is what refuses them.
pub fn admissible(manifest: &Manifest, floor: Floor) -> Result<(), Refusal> {
    if manifest.key_epoch < floor.epoch {
        return Err(Refusal::EpochBelowFloor { epoch: manifest.key_epoch, floor: floor.epoch });
    }
    // Only compared within the same epoch. A higher epoch that verifies is a
    // rotation, and a rotation resets the seq floor to zero -- the epoch bump is
    // itself the anti-rollback guarantee from that point, since `floor_epoch`
    // has advanced and nothing below it will ever verify again.
    if manifest.key_epoch == floor.epoch && manifest.seq <= floor.seq {
        return Err(Refusal::BelowFloor { seq: manifest.seq, floor: floor.seq });
    }
    Ok(())
}

/// What `--version` prints, as a string so it can be tested.
///
/// `main.rs` is the crate root of a binary-only crate, so nothing in it is
/// reachable from a unit test. The formatting therefore lives here and `main`
/// only prints it -- which matters because CI greps this output for the build
/// ordinal, and a change to the wording would break the release pipeline with
/// no test anywhere objecting.
///
/// Flat `key = value`, the same shape `paths::entries` parses, so this output,
/// the signed manifest, `update.conf` and `update.state` all read alike.
pub fn version_report() -> String {
    let build = match crate::app::build_number() {
        Some(build) => build.to_string(),
        // `none`, never `0`. A stamp that failed to parse must not compare as a
        // number: `grep -qx "build = 0"` succeeding on a broken build is exactly
        // the false green the readback exists to prevent.
        None => "none".to_string(),
    };
    format!(
        "version = {}\nbuild = {}\ncommit = {}\n",
        env!("CARGO_PKG_VERSION"),
        build,
        crate::app::build_commit()
    )
}

/// The URL a verified payload is fetched from.
///
/// Built here and nowhere else, so the compiled-in prefix is the only thing that
/// can ever decide the host. The name has already been through
/// [`valid_payload_name`] by the time a [`Payload`] exists.
pub fn payload_url(payload: &Payload) -> String {
    format!("{DOWNLOAD_PREFIX}{}", payload.name)
}

/// Stream `reader` into `sink`, checking the length and the digest as it goes.
///
/// **The absolute cap is applied before the signed size, not instead of it.**
/// A body is bounded by [`MAX_UPDATE_BYTES`] first and by `payload.size`
/// second; using the declared size as the only bound would let anyone who can
/// answer the request make us stream gigabytes into the user's directory before
/// the digest failed. The digest is computed over exactly the bytes written, so
/// there is no window between "verified" and "used" -- what is checked is what
/// lands.
///
/// SHA-256 from `ring`, which is already compiled as rustls' backend. Hand
/// rolling it here is forbidden: this is the check that decides whether network
/// bytes get the execute bit.
pub fn check_payload(
    mut reader: impl std::io::Read,
    payload: &Payload,
    sink: &mut impl std::io::Write,
) -> Result<(), Refusal> {
    if payload.size > MAX_UPDATE_BYTES {
        return Err(Refusal::TooLarge { what: "update payload", cap: MAX_UPDATE_BYTES });
    }
    let mut context = ring::digest::Context::new(&ring::digest::SHA256);
    let mut written: u64 = 0;
    let mut buffer = [0u8; 64 * 1024];
    loop {
        let read = reader.read(&mut buffer).map_err(|why| Refusal::Unreachable(why.to_string()))?;
        if read == 0 {
            break;
        }
        // Refused the moment it exceeds rather than after buffering the rest,
        // so an over-long body costs one chunk of slack and no more.
        written += read as u64;
        if written > payload.size {
            return Err(Refusal::PayloadSizeMismatch { declared: payload.size, actual: written });
        }
        context.update(&buffer[..read]);
        sink.write_all(&buffer[..read]).map_err(|why| Refusal::Unreachable(why.to_string()))?;
    }
    // Short is as wrong as long. The digest would catch a truncated download
    // anyway; naming the length properly means a network fault reports as one
    // rather than as a digest mismatch, which reads like tampering.
    if written != payload.size {
        return Err(Refusal::PayloadSizeMismatch { declared: payload.size, actual: written });
    }
    let digest = context.finish();
    let actual: String = digest.as_ref().iter().map(|byte| format!("{byte:02x}")).collect();
    // Constant time is not needed: the expected digest came out of a manifest
    // that has already been authenticated, so there is no secret here to leak.
    if actual != payload.sha256 {
        return Err(Refusal::DigestMismatch { expected: payload.sha256.clone(), actual });
    }
    Ok(())
}

/// Whether the running build is one the manifest marks as known-bad.
///
/// **Strictly below**, so a client *at* the minimum meets it and is left alone,
/// which is what the name says. In build space against the running ordinal,
/// never against `seq`: after a rollback the two have diverged by construction.
pub fn below_minimum(manifest: &Manifest, running: u64) -> bool {
    running < manifest.minimum_build
}

/// What the interface is told, once everything above has agreed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Offer {
    /// The ordinal being offered. May be **lower** than the running build: a
    /// rollback publishes a higher `seq` naming an older `build`, and the UI
    /// must not call that an upgrade.
    pub build: u64,
    /// The ordinal actually running, so the message can name both.
    pub running: u64,
    /// The running build is below `minimum_build`. Shown even when the user has
    /// skipped this build: "not now" answers an offer, not a warning.
    pub known_bad: bool,
    /// This build cannot be reached by replacing one executable, so the user is
    /// sent to the release page rather than offered an in-place update.
    pub requires_reinstall: bool,
    /// The payload this platform would download, carried through from the
    /// verified manifest so accepting the offer needs no second fetch -- and,
    /// more importantly, so the bytes that get downloaded are described by the
    /// same signed manifest that was checked, not by a later one that might
    /// have changed underneath.
    ///
    /// `None` when the manifest names no payload for this platform, which is an
    /// ordinary outcome: the offer is still worth showing, it just cannot be
    /// acted on here.
    pub payload: Option<Payload>,
    /// The manifest's own counter, carried so a successful apply can raise the
    /// anti-rollback floor to it. **Manifest space, never build space.**
    pub seq: u64,
    /// Which key signed the manifest this offer came from, for the same reason.
    pub key_epoch: u32,
}

impl Offer {
    /// Worded without claiming a direction unless one is known.
    pub fn headline(&self) -> String {
        if self.known_bad {
            format!("build {} has a known problem; build {} fixes it", self.running, self.build)
        } else if self.build > self.running {
            format!("Build {} is out — you are on {}", self.build, self.running)
        } else {
            format!("Build {} is being republished — you are on {}", self.build, self.running)
        }
    }
}

/// When the check may run.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum When {
    /// Never. The packager kill switch also lands here.
    Never,
    /// Only while the welcome screen is up, alongside the articles.
    Welcome,
    /// Every launch. **The default**, settled 2026-08-30: it matches what the
    /// old unconditional check did and adds a switch where there was none, and
    /// the person who most needs to hear their build is stale is the one who
    /// turned the welcome screen off.
    #[default]
    Always,
}

/// `update.conf`, as read from the config directory.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Settings {
    pub when: When,
    /// A build the user said "not now" to. A *newer* one still offers -- which
    /// is the thing SindriCAD lacks, where declining is not remembered and the
    /// modal returns eight seconds into every session.
    pub skip_build: Option<u64>,
}

/// The packager kill switch, Zed's pattern. Set it and the whole update surface
/// is replaced by the packager's text -- and the **check does not run either**, a
/// distro build that keeps polling GitHub to display nothing being a connection
/// nobody asked for and nobody can see.
const EXPLANATION_VARIABLE: &str = "BROKKR_UPDATE_EXPLANATION";

/// Parse `update.conf`. Lenient in the house style of `printer.rs` and
/// `spacemouse.rs`: this is the user's own file, not attacker bytes, so an
/// unreadable value falls back to the default rather than refusing to launch.
pub fn settings_from(text: &str) -> Settings {
    let mut settings = Settings::default();
    for (key, value) in crate::paths::entries(text) {
        match key {
            "check_for_updates" => {
                settings.when = match value {
                    "never" => When::Never,
                    "welcome" => When::Welcome,
                    "always" => When::Always,
                    _ => settings.when,
                }
            }
            "skip_build" => settings.skip_build = value.parse().ok(),
            _ => {}
        }
    }
    settings
}

/// Read `update.conf`, or the defaults if there is none.
pub fn settings() -> Settings {
    if std::env::var_os(EXPLANATION_VARIABLE).is_some() {
        return Settings { when: When::Never, skip_build: None };
    }
    crate::paths::config_file("update.conf")
        .and_then(|path| std::fs::read_to_string(path).ok())
        .map_or_else(Settings::default, |text| settings_from(&text))
}

/// Render settings back to the file's text.
///
/// Split from the write so it can be tested without a path, which is the shape
/// `printer.rs`, `welcome.rs` and `crash.rs` all use -- `paths.rs` reads the
/// environment at call time and the suite runs in parallel, so a test that wrote
/// through the real path would reach into the config of whoever ran it.
pub fn settings_text(settings: &Settings) -> String {
    let when = match settings.when {
        When::Never => "never",
        When::Welcome => "welcome",
        When::Always => "always",
    };
    let mut text = format!(
        "# BrokkrSculpt update checks.\n\
         # never   -- do not check at all\n\
         # welcome -- only while the welcome screen is up\n\
         # always  -- every launch (the default)\n\
         check_for_updates = {when}\n"
    );
    if let Some(build) = settings.skip_build {
        // A build the user declined. A NEWER one still offers; this is not a
        // permanent off switch, and the comment says so because the next person
        // to read this file will otherwise assume it is one.
        text.push_str(&format!(
            "# A build that was declined. A newer one is still offered.\n\
             skip_build = {build}\n"
        ));
    }
    text
}

/// Remember the answer. A write that fails is dropped, like `welcome.rs`: the
/// preference is worth less than the session, and there is nothing useful to say
/// about a read-only config directory in the middle of a click.
pub fn store(settings: &Settings) {
    let Some(path) = crate::paths::config_file("update.conf") else {
        return;
    };
    if let Some(parent) = path.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(path, settings_text(settings));
}

/// Parse `update.state`.
///
/// Absent, unreadable or malformed all give the same answer: a zero floor. That
/// is the documented reset -- "delete `update.state`" -- and it must therefore
/// be a *recoverable* state rather than a refusal, because the user performing
/// it has no terminal to read an error in.
pub fn floor_from(text: &str) -> Floor {
    let mut floor = Floor::default();
    for (key, value) in crate::paths::entries(text) {
        match key {
            "floor_epoch" => floor.epoch = value.parse().unwrap_or(0),
            "floor_seq" => floor.seq = value.parse().unwrap_or(0),
            _ => {}
        }
    }
    floor
}

/// Remember the digest of the build being replaced, so the revert can refuse to
/// run whatever happens to be sitting at `.old`.
///
/// Written beside the floor in `update.state`. A failure is dropped rather than
/// aborting the update: the consequence is that a revert will refuse for want of
/// a digest, which is the safe direction.
pub fn record_previous(sha256: &str) {
    record_state(Some(sha256), None, None);
}

/// Rewrite `update.state`, preserving what is not being changed.
///
/// One writer for the whole file, because a read-modify-write per field would
/// let two of them race and drop each other's line. Everything here is under the
/// `update.lock` in practice; this is the shape that makes that lock sufficient.
fn record_state(previous: Option<&str>, installed: Option<u64>, checked: Option<u64>) {
    let Some(path) = crate::paths::state_file("update.state") else {
        return;
    };
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    let keep = |name: &str| {
        crate::paths::entries(&existing)
            .find(|(key, _)| *key == name)
            .map(|(_, value)| value.to_string())
    };
    let floor = floor();
    let previous = previous.map(str::to_string).or_else(|| keep("previous_sha256"));
    let installed = installed.map(|n| n.to_string()).or_else(|| keep("installed_build"));
    let checked = checked.map(|n| n.to_string()).or_else(|| keep("last_check"));

    let mut text = format!("floor_epoch = {}\nfloor_seq = {}\n", floor.epoch, floor.seq);
    if let Some(previous) = previous {
        text.push_str(&format!("previous_sha256 = {previous}\n"));
    }
    if let Some(installed) = installed {
        // Machine readable, and deliberately NOT `last_outcome`: that one is
        // prose for the About panel and must not quietly become a flag.
        text.push_str(&format!("installed_build = {installed}\n"));
    }
    if let Some(checked) = checked {
        text.push_str(&format!("last_check = {checked}\n"));
    }
    if let Some(parent) = path.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(path, text);
}

/// Record a successful apply: raise the floor, and remember what was installed.
///
/// **The floor advances here and nowhere else.** Not on merely seeing an offer,
/// which is what stops someone who can show a client a manifest from moving its
/// floor by doing so — and not never, which is what an earlier revision did.
/// The first real update on this machine installed correctly and left
/// `floor_seq = 0`, so the install would have accepted an older manifest
/// afterwards. Nothing in the suite caught it, because every test drove the
/// pure functions rather than the apply path.
///
/// `installed_build` is written in the same breath because the crash-driven
/// revert offer compares the running ordinal against it, and an absent value
/// silently means "never offer".
pub fn record_applied(seq: u64, key_epoch: u32, build: u64) {
    let Some(path) = crate::paths::state_file("update.state") else {
        return;
    };
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    let keep = |name: &str| {
        crate::paths::entries(&existing)
            .find(|(key, _)| *key == name)
            .map(|(_, value)| value.to_string())
    };
    let mut text =
        format!("floor_epoch = {key_epoch}\nfloor_seq = {seq}\ninstalled_build = {build}\n");
    if let Some(previous) = keep("previous_sha256") {
        text.push_str(&format!("previous_sha256 = {previous}\n"));
    }
    if let Some(checked) = keep("last_check") {
        text.push_str(&format!("last_check = {checked}\n"));
    }
    if let Some(parent) = path.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(path, text);
}

/// Note that a check succeeded, for freshness only.
///
/// **The only clock value this design stores, and it is displayed rather than
/// compared against any rule.** That is the whole difference from the `expires`
/// field this plan rejected: a stale `last_check` produces a line in the Help
/// panel, never a refusal, so a machine with a wrong clock loses a sentence and
/// not its updates.
pub fn record_check_succeeded() {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|since| since.as_secs())
        .unwrap_or_default();
    record_state(None, None, Some(now));
}

/// One line for the diagnostics and the About panel: what the updater is set
/// to, what it last installed, and how fresh the last successful check is.
pub fn outcome_line() -> String {
    let settings = settings();
    let when = match settings.when {
        When::Never => "off",
        When::Welcome => "with the welcome screen",
        When::Always => "on",
    };
    let installed = installed_build()
        .map_or_else(|| "never self-updated".to_string(), |n| format!("installed build {n}"));
    let skipped = settings.skip_build.map_or_else(String::new, |n| format!(", skipping {n}"));
    format!("{when}, {installed}{skipped}, {}", freshness_line())
}

/// The ordinal this install last put in place, if any.
///
/// Read from `installed_build` rather than from `last_outcome`: that one is
/// prose for the About panel and must not quietly become a machine-readable
/// flag, because the day someone reworded it the comparison would start
/// failing silently.
pub fn installed_build() -> Option<u64> {
    let text = crate::paths::state_file("update.state")
        .and_then(|path| std::fs::read_to_string(path).ok())?;
    crate::paths::entries(&text)
        .find(|(key, _)| *key == "installed_build")
        .and_then(|(_, value)| value.parse().ok())
}

/// The Help panel's one line about update freshness.
///
/// Read once at startup and not refreshed, so a check that succeeds during this
/// session does not change it until the next launch. That is a deliberate
/// trade -- it changes once a day and re-reading a file per frame to say so
/// would be absurd -- but it means a first run reads "no update check has
/// succeeded yet" for the whole session even after one has.
pub fn freshness_line() -> String {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|since| since.as_secs())
        .unwrap_or_default();
    let text = crate::paths::state_file("update.state")
        .and_then(|path| std::fs::read_to_string(path).ok())
        .unwrap_or_default();
    match days_since_check(&text, now) {
        None => "no update check has succeeded yet".to_string(),
        Some(0) => "checked for updates today".to_string(),
        Some(1) => "last update check: yesterday".to_string(),
        Some(days) => format!("last update check: {days} days ago"),
    }
}

/// How long since a check last succeeded, in whole days.
///
/// `None` when none ever has, or when the stored value is in the future --
/// which a wrong clock can produce, and which must read as "unknown" rather
/// than as a negative number of days.
pub fn days_since_check(text: &str, now: u64) -> Option<u64> {
    let last: u64 = crate::paths::entries(text)
        .find(|(key, _)| *key == "last_check")
        .and_then(|(_, value)| value.parse().ok())?;
    now.checked_sub(last).map(|seconds| seconds / 86_400)
}

/// The digest recorded before the last apply, if there is one.
pub fn previous_sha256_from(text: &str) -> Option<String> {
    crate::paths::entries(text)
        .find(|(key, _)| *key == "previous_sha256")
        .map(|(_, value)| value.to_string())
}

/// Read the persisted floor.
pub fn floor() -> Floor {
    crate::paths::state_file("update.state")
        .and_then(|path| std::fs::read_to_string(path).ok())
        .map_or_else(Floor::default, |text| floor_from(&text))
}

/// How many redirects to follow. GitHub currently uses exactly one.
const MAX_REDIRECTS: usize = 3;

/// Named so a proxy log on someone's own network says who is calling. GitHub
/// also refuses a request with no user agent.
const USER_AGENT: &str = "BrokkrSculpt";

/// Long enough for two small files on a bad line, short enough that nothing the
/// user is doing waits on it. Only ever applied to the manifest and its
/// signature, both capped in the tens of kilobytes -- the payload download in
/// Phase 2 must NOT reuse this, because a wall-clock budget over 33 MB fails
/// every connection under about 13 Mbit/s, permanently and silently.
const META_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(20);

/// Whether a redirect may be followed to this host.
///
/// **`github.com` is an equality test and not a suffix**, because
/// `evilgithub.com` ends with `github.com`. The leading dot on the other arm
/// does the same work: `evil-githubusercontent.com` does not end with
/// `.githubusercontent.com`.
///
/// Measured 2026-08-30, the real chain is one hop from `github.com` to
/// `release-assets.githubusercontent.com` -- **not** `objects.githubusercontent.com`,
/// which is where GitHub used to send these. Naming a single host here would
/// have refused every download on every install, unfixable through the channel
/// it broke, so the rule is by suffix on that domain.
fn host_is_allowed(host: &str) -> bool {
    if !host.is_ascii() {
        return false;
    }
    let host = host.to_ascii_lowercase();
    host == "github.com" || host.ends_with(".githubusercontent.com")
}

/// The host part of an absolute https URL, if it has one.
fn host_of(url: &str) -> Option<&str> {
    let rest = url.strip_prefix("https://")?;
    let end = rest.find(['/', '?', '#']).unwrap_or(rest.len());
    let authority = &rest[..end];
    // No credentials in the authority: `https://github.com@evil.example/` has a
    // host of `evil.example`, and a naive prefix test would read it as GitHub.
    if authority.contains('@') {
        return None;
    }
    let host = authority.split(':').next()?;
    (!host.is_empty()).then_some(host)
}

/// GET a small file, following redirects by hand.
///
/// Nothing stores the redirect target. GitHub's 302 lands on a signed URL good
/// for about an hour, so a cached one is a bug with a one-hour fuse: green in
/// every test, failing the first time someone leaves a dialog open over lunch.
/// Follow redirects by hand and hand back the response, ready to read.
///
/// **By hand, because the obvious mechanism silently does not work.** ureq's
/// middleware hook wraps `run()` and the redirect loop lives *inside* `run()`,
/// so a middleware allowlist would see the first request and no other while
/// looking entirely correct. `max_redirects(0)` returns the 3xx as an ordinary
/// response instead, so the host can be checked on every hop -- and each hop
/// being its own call is also what makes `https_only` bite per hop rather than
/// once.
///
/// Nothing stores the redirect target: it is a signed URL good for about an
/// hour, so a cached one is a bug with a one-hour fuse.
fn follow_to_body(
    agent: &ureq::Agent,
    url: &str,
    what: &'static str,
) -> Result<ureq::http::Response<ureq::Body>, Refusal> {
    let mut current = url.to_string();
    for _ in 0..=MAX_REDIRECTS {
        match host_of(&current) {
            Some(host) if host_is_allowed(host) => {}
            _ => return Err(Refusal::Unreachable(format!("refused to follow {what} off GitHub"))),
        }
        let response = agent
            .get(&current)
            .header("User-Agent", USER_AGENT)
            .call()
            .map_err(|why| Refusal::Unreachable(why.to_string()))?;

        let status = response.status().as_u16();
        if (300..400).contains(&status) {
            let location = response
                .headers()
                .get("location")
                .and_then(|value| value.to_str().ok())
                .ok_or_else(|| Refusal::Unreachable("a redirect with no location".into()))?;
            // Absolute only. A relative redirect is legal HTTP and GitHub does
            // not send one; resolving it would mean writing a URL joiner, and a
            // wrong one here re-opens exactly the hole the allowlist closes.
            if !location.starts_with("https://") {
                return Err(Refusal::Unreachable("a redirect that was not absolute https".into()));
            }
            current = location.to_string();
            continue;
        }
        return Ok(response);
    }
    Err(Refusal::Unreachable(format!("{what} redirected more than {MAX_REDIRECTS} times")))
}

/// GET a small file whole, under an absolute cap.
fn get_capped(
    agent: &ureq::Agent,
    url: &str,
    cap: u64,
    what: &'static str,
) -> Result<Vec<u8>, Refusal> {
    use std::io::Read;

    let mut response = follow_to_body(agent, url, what)?;
    // `as_reader()` is NOT used: it carries a hidden 10 MiB cap that would
    // surface as a network-looking error rather than as a size refusal.
    let mut body = Vec::new();
    response
        .body_mut()
        .with_config()
        .limit(cap + 1)
        .reader()
        .take(cap + 1)
        .read_to_end(&mut body)
        .map_err(|why| Refusal::Unreachable(why.to_string()))?;
    if body.len() as u64 > cap {
        return Err(Refusal::TooLarge { what, cap });
    }
    Ok(body)
}

/// The whole check, start to finish. Blocking: call it off the interface thread.
///
/// Returns `Ok(None)` for "nothing to say", which is the common case and is not
/// an error. Every refusal is named so the caller can decide what is worth a
/// status line -- most are not.
pub fn check(
    running: Option<u64>,
    settings: &Settings,
    floor: Floor,
) -> Result<Option<Offer>, Refusal> {
    // **The updater is structurally inert on anything but a release build.**
    // `None` covers a local build, a source build and a failed stamp; the dirty
    // and unknown checks are free and they are the difference between "inert"
    // and "one keypress away from overwriting the developer's own binary".
    let running = running.ok_or(Refusal::NotAReleaseBuild)?;
    let commit = crate::app::build_commit();
    if commit == "unknown" || commit.ends_with("-dirty") {
        return Err(Refusal::NotAReleaseBuild);
    }
    if settings.when == When::Never {
        return Ok(None);
    }
    if platform_slug().is_none() {
        return Err(Refusal::UnsupportedPlatform);
    }

    let agent: ureq::Agent = ureq::Agent::config_builder()
        .timeout_global(Some(META_TIMEOUT))
        // ureq's default is `false`, so without this a redirect to plain http
        // is followed -- and these URLs do redirect.
        .https_only(true)
        // Followed by hand instead; see `get_capped`.
        .max_redirects(0)
        .build()
        .into();

    let body = get_capped(&agent, MANIFEST_URL, MAX_MANIFEST_BYTES, "update manifest")?;
    let signature = get_capped(&agent, SIGNATURE_URL, MAX_SIGNATURE_BYTES, "update signature")?;

    let manifest = verify_manifest(&body, &signature)?;
    // Recorded on a successful FETCH AND VERIFY, before the floor is consulted:
    // an offer refused by the floor still proves the channel is answering, and
    // that is the only thing this value is for.
    record_check_succeeded();
    admissible(&manifest, floor)?;

    let known_bad = below_minimum(&manifest, running);
    // The offer is suppressed by `skip_build`; the warning is not. "Not now" is
    // an answer to an offer and not to "the build you are on is broken".
    if !known_bad && (manifest.build == running || Some(manifest.build) == settings.skip_build) {
        return Ok(None);
    }
    Ok(Some(Offer {
        build: manifest.build,
        running,
        known_bad,
        requires_reinstall: manifest.requires_reinstall,
        payload: manifest.payload,
        seq: manifest.seq,
        key_epoch: manifest.key_epoch,
    }))
}

/// Where a downloaded payload is put.
///
/// The state directory, not `/tmp`: a cross-filesystem rename degrades to a
/// copy, and copy-over-a-running-image is precisely the operation that fails on
/// both Linux and Windows. Phase 3 replaces in place from here, so getting the
/// filesystem right now costs nothing and saves a rewrite.
pub fn download_directory() -> Option<std::path::PathBuf> {
    crate::paths::state_file("updates")
}

/// Fetch the offered payload, verify it, and leave it on disk.
///
/// **This is the whole of Phase 2, and it deliberately stops here.** Nothing is
/// made executable, nothing is replaced and nothing restarts. It is the
/// permanent macOS answer -- where the unit of replacement is a signed bundle
/// and editing one can turn a working install into an unlaunchable one -- and
/// the interim answer everywhere else.
///
/// Returns where the file landed, so the caller can tell the user. A user who
/// is handed a verified file and not told where it is has been given nothing.
pub fn download(offer: &Offer, into: &std::path::Path) -> Result<std::path::PathBuf, Refusal> {
    let payload = offer.payload.as_ref().ok_or(Refusal::UnsupportedPlatform)?;
    // **Which directory is a correctness question, not a tidiness one.**
    // `install` finishes with `rename(staged, target)`, and a cross-filesystem
    // rename degrades to a copy -- which is precisely the operation that fails
    // against a running image. So an install stages beside the binary and a
    // hand-over stages in the state directory, and the caller picks.
    let directory = into.to_path_buf();
    std::fs::create_dir_all(&directory)
        .map_err(|why| Refusal::Unreachable(format!("could not make {directory:?} ({why})")))?;

    // **A separate agent from the manifest's, and it sets no wall-clock limit.**
    // `timeout_global` covers the body, so 20 s over a 33 MB payload demands
    // 13.4 Mbit/s sustained and fails every slower connection for ever, in
    // silence. `timeout_recv_body` is a rolling stall timer rather than a
    // deadline -- it is recomputed on every read poll -- so a slow line is
    // allowed to finish while a dead socket is not. `timeout_recv_response` is
    // deliberately unset: it is also checked while reading the body, so setting
    // it would silently cap the download.
    let agent: ureq::Agent = ureq::Agent::config_builder()
        .timeout_resolve(Some(std::time::Duration::from_secs(10)))
        .timeout_connect(Some(std::time::Duration::from_secs(10)))
        .timeout_send_request(Some(std::time::Duration::from_secs(20)))
        .timeout_recv_body(Some(std::time::Duration::from_secs(30)))
        .https_only(true)
        .max_redirects(0)
        .build()
        .into();

    // Every attempt starts at byte zero and re-derives its URL. The 302 lands
    // on a signed URL good for about an hour, so a stored one is a bug with a
    // one-hour fuse: green in every test, failing the first time someone leaves
    // the dialog open over lunch.
    let url = payload_url(payload);
    let mut response = follow_to_body(&agent, &url, "update payload")?;

    // Into a `.part` first, created `O_EXCL` at 0600 and `O_NOFOLLOW`, so a
    // failed or refused download never leaves something at the final path that
    // looks complete, unverified bytes are never world-readable while they are
    // being written, and a symlink planted at that name is never followed.
    let (partial, mut file) = apply::stage_in(&directory, &payload.name)?;
    let final_path = directory.join(&payload.name);

    let outcome = check_payload(
        response.body_mut().with_config().limit(MAX_UPDATE_BYTES).reader(),
        payload,
        &mut file,
    );
    if let Err(why) = outcome {
        // Nothing verified is left lying about under a name suggesting it was.
        drop(file);
        let _ = std::fs::remove_file(&partial);
        return Err(why);
    }
    // Executable and flushed only AFTER the digest matched. Creating it 0755 and
    // then filling it with unverified network bytes would invert the point of
    // staging it private in the first place, and `~/.local/bin` is on `PATH` on
    // most distributions.
    apply::finish_staging(&file)?;
    drop(file);
    std::fs::rename(&partial, &final_path).map_err(|why| {
        let _ = std::fs::remove_file(&partial);
        Refusal::Unreachable(format!("could not finish the download ({why})"))
    })?;
    Ok(final_path)
}

